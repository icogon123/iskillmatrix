import mongoose from 'mongoose';

const incomeRunSchema = new mongoose.Schema(
  {
    type: { type: String, enum: ['weekly', 'monthly_bonus', 'royalty'], required: true },
    periodKey: { type: String, required: true },
    periodStart: Date,
    periodEnd: Date,
    status: { type: String, enum: ['generated', 'approved', 'cancelled'], default: 'generated', index: true },
    itemsCount: { type: Number, default: 0 },
    totalAmount: { type: Number, default: 0 },
    generatedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    approvedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    approvedAt: Date,
    cancelledBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    cancelledAt: Date,
    settingsVersion: Number,
    // auto: generated by the scheduler when the week closed.
    trigger: { type: String, enum: ['manual', 'auto'], default: 'manual' },
    // Weekly runs: percent × company sales in the week, shared equally by `eligible` members.
    pool: {
      basis: String,
      salesCount: Number,
      companyIncome: Number,
      percent: Number,
      amount: Number,
      eligible: Number,
      share: Number,
    },
    // `${type}:${periodKey}` while not cancelled: one live run per period.
    activeKey: { type: String, unique: true, sparse: true },
  },
  { timestamps: true },
);

export default mongoose.model('IncomeRun', incomeRunSchema);
